    ("Завтрак", "Яйца", "2 шт.", 12.0, 10.0, 1.0),
    ("Завтрак", "Сывороточный протеин", "30 г", 24.0, 2.0, 3.0),
    ("Обед", "Куриная грудка", "170 г", 52.7, 6.0, 0.0),
    ("Обед", "Гречка, готовая", "80 г", 2.7, 0.5, 16.0),
    ("Обед", "Овощи", "200 г", 4.0, 0.0, 12.0),
    ("Обед", "Оливковое масло", "10 г", 0.0, 10.0, 0.0),
    ("Перекус", "Творог 5%", "180 г", 28.8, 9.0, 5.4),
    ("Перекус", "Яблоко", "1 среднее", 0.0, 0.0, 21.0),
    ("Перекус", "Орехи", "25 г", 5.0, 12.5, 5.0),
    ("Ужин", "Белая рыба", "190 г", 39.9, 13.3, 0.0),
